// Turns the --ds-chart-series-N-color declarations into the TypeScript palette the
// components read. `--check` fails instead of writing, so a token renamed in the SCSS
// without a regenerate cannot ship: the stale file still compiles, and the only place
// the mismatch shows is a colour that stopped resolving in a browser.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(ROOT, 'src/lib/styles/_tokens-charts.scss');
const OUT = join(ROOT, 'src/lib/components/chart-palette.generated.ts');

const scss = readFileSync(SOURCE, 'utf8');
const numbered = (family) => {
  const found = [
    ...scss.matchAll(
      new RegExp(`^\\s*(--ds-chart-${family}-(\\d+)-color):`, 'gm'),
    ),
  ]
    .map((match) => ({ token: match[1], number: Number(match[2]) }))
    .sort((a, b) => a.number - b.number);
  if (found.length === 0)
    throw new Error(`no --ds-chart-${family}-N-color tokens found`);

  const numbers = found.map((match) => match.number);
  if (!numbers.every((number, index) => number === index + 1)) {
    throw new Error(
      `--ds-chart-${family}-N-color tokens must be numbered 1..N with no gaps or duplicates; ` +
        `found [${numbers.join(', ')}], expected 1..${found.length}`,
    );
  }

  return found.map((match) => match.token);
};

const series = numbered('series');
const ramp = numbered('ramp');
const heat = numbered('heat');

// The two named series tokens are not part of either array: `default` and `accent` are
// roles, so a chart asks for one by name. Folding them into CHART_SERIES_COLORS would
// hand them out to whichever series happened to land on that index.
const named = ['default', 'accent'].map((role) => {
  const token = `--ds-chart-series-${role}-color`;
  if (!scss.includes(`${token}:`))
    throw new Error(`${token} is missing from the contract layer`);

  return token;
});

// A CSS custom-property name cannot be used in TypeScript, so strip the namespace
// and camel-case what is left: --ds-chart-series-3-color -> series3.
const key = (token) =>
  token
    .replace(/^--ds-chart-/, '')
    .replace(/-color$/, '')
    .replace(/-(\w)/g, (_, character) => character.toUpperCase());

const entries = [...series, ...named, ...ramp, ...heat]
  .map((token) => `  ${key(token)}: 'var(${token})',`)
  .join('\n');

const arrayOf = (name, tokens) =>
  `/** @internal See chartColors. */\nexport const ${name}: readonly string[] = [\n` +
  tokens.map((token) => `  chartColors.${key(token)},\n`).join('') +
  `];\n`;

const generated =
  `// GENERATED by tools/generate-chart-palette.mjs. Do not edit. Values are var()\n` +
  `// references, not resolved colours, so a consumer overriding the token still wins\n` +
  `// at runtime.\n\n` +
  `/** @internal Exported for the chart entry points that import it across the boundary;\n *  not part of the package surface. */\nexport const chartColors = {\n${entries}\n} as const;\n\n` +
  arrayOf('CHART_SERIES_COLORS', series) +
  `\n` +
  arrayOf('CHART_RAMP_COLORS', ramp) +
  `
` +
  arrayOf('CHART_HEAT_COLORS', heat);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    console.error(
      'generate-chart-palette: src/lib/components/chart-palette.generated.ts is missing. Run `npm run generate-chart-palette`.',
    );
    process.exit(1);
  }
  if (current !== generated) {
    console.error(
      'generate-chart-palette: chart-palette.generated.ts is out of step with _tokens-charts.scss.\n' +
        '  Run `npm run generate-chart-palette` and commit the result.',
    );
    process.exit(1);
  }
  console.log(
    `generate-chart-palette: OK — ${series.length + named.length + ramp.length + heat.length} colours match the SCSS.`,
  );
} else {
  writeFileSync(OUT, generated);
  console.log(
    `generate-chart-palette: wrote ${series.length + named.length + ramp.length + heat.length} colours`,
  );
}
