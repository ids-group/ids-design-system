#!/usr/bin/env node
// The package facade, built from the entry points instead of maintained by hand.
//
// Why generate it: 124 export statements ordered by hand drift, and a new entry point is easy to
// forget — the facade is the only thing that makes a component reachable from the package root.
//
// What it is NOT: a mirror. The entry points export 183 values where the facade publishes 129,
// because an entry point has to export whatever a SIBLING entry point imports. Those helpers are
// reachable without being part of the package surface, and two things keep them out:
//
//   - `@internal` on the declaration, which `internalSymbols()` collects. This is the mechanism to
//     use for anything new.
//   - ROOT_PRIVATE below, for symbols that predate the tag and belong to features whose owners
//     have not been asked yet. It is a holding pen, not a design — empty it by tagging.
//
//   node tools/generate-public-api.mjs           write src/lib/public-api.ts
//   node tools/generate-public-api.mjs --check   fail if the file is stale, write nothing
import { readFileSync, writeFileSync } from 'node:fs';
import { entryPoints, internalSymbols, FACADE, PACKAGE_NAME } from './lib-entry-points.mjs';

// Exported by an entry point, withheld from the facade, not yet tagged. Each needs its owner to
// say whether it is internal or should be published; until then the generator must not promote it.
const ROOT_PRIVATE = new Set([
  'DsDestination',
  'DsLinkModifiers',
  'DsTableColumnStage',
  'DsTableExportContribution',
  'DsTableRowStage',
  'DsTableView',
]);

// A group's heading in the emitted file, chosen by entry-point path. First match wins, so the
// specific prefixes come before the general one.
const GROUPS = [
  ['Core', (id) => id.endsWith('/core')],
  ['Theme', (id) => id.endsWith('/theme')],
  ['Icons', (id) => id.endsWith('/icons')],
  ['Overlay', (id) => id.endsWith('/overlay')],
  ['Shared component contracts', (id) => id.endsWith('/components')],
  ['Components', (id) => id.includes('/components/')],
  ['Other', () => true],
];

/** A name and whether it crosses as a type. `export { A, type B }` and `export type { B }` mean
 *  the same thing, so classify by the modifier on the NAME, never by which block it sits in. */
function parseExports(source) {
  const found = [];
  for (const [, blockIsType, body] of source.matchAll(
    /export\s+(type\s+)?\{([^}]*)\}\s*from\s*'[^']+'/g,
  )) {
    for (const raw of body.split(',')) {
      const name = raw.trim();
      if (!name) continue;
      found.push({
        name: name.replace(/^type\s+/, ''),
        isType: Boolean(blockIsType) || /^type\s+/.test(name),
      });
    }
  }
  return found;
}

function build() {
  const hidden = internalSymbols();
  const lines = [
    '// GENERATED by tools/generate-public-api.mjs from each entry point index.',
    '// Do not edit. A symbol is published here unless it carries @internal.',
  ];

  // Five symbols are exported by a component AND by `core` — CardElevation, CardPadding and the
  // three DsToast positions. Re-exporting both spellings is `TS2300: Duplicate identifier`, so the
  // facade may name each once. `entryPoints()` sorts by module id, which puts `/components/card`
  // and `/components/toast` before `/core`, so first-wins picks the component — the same choice
  // the hand-written facade made for all five.
  const claimed = new Set();

  let openGroup = null;
  for (const entry of entryPoints()) {
    const exported = parseExports(readFileSync(entry.index, 'utf8')).filter(
      (item) =>
        !hidden.has(item.name) && !ROOT_PRIVATE.has(item.name) && !claimed.has(item.name),
    );
    for (const item of exported) claimed.add(item.name);
    if (!exported.length) continue;

    const group = GROUPS.find(([, matches]) => matches(entry.moduleId))[0];
    if (group !== openGroup) {
      lines.push('', `// ${group}`);
      openGroup = group;
    }

    const values = exported.filter((item) => !item.isType).map((item) => item.name).sort();
    const types = exported.filter((item) => item.isType).map((item) => item.name).sort();
    for (const [names, keyword] of [
      [values, 'export'],
      [types, 'export type'],
    ]) {
      if (!names.length) continue;
      const single = `${keyword} { ${names.join(', ')} } from '${entry.moduleId}';`;
      // Prettier never splits a block holding ONE specifier, however long the module path makes
      // the line — so neither may this, or `format` fails on the file it just generated.
      lines.push(
        names.length === 1 || single.length <= 80
          ? single
          : `${keyword} {\n  ${names.join(',\n  ')},\n} from '${entry.moduleId}';`,
      );
    }
  }

  return lines.join('\n') + '\n';
}

const next = build();
const checking = process.argv.includes('--check');
const current = readFileSync(FACADE, 'utf8');

if (checking) {
  if (current === next) {
    console.log('generate-public-api: public-api.ts is current.');
    process.exit(0);
  }
  console.error(
    'generate-public-api: public-api.ts is stale — run `node tools/generate-public-api.mjs`.',
  );
  process.exit(1);
}

writeFileSync(FACADE, next);
const count = next.split('\n').filter((line) => line.startsWith('export')).length;
console.log(`generate-public-api: wrote ${count} export statement(s) for ${PACKAGE_NAME}.`);
