// Generates ds-docs/src/ds-statuses.d.ts, the DsStatusRegistry augmentation that makes
// <ds-badge status="…"> autocomplete in ds-docs, from the statuses ds-docs/src/styles.scss
// actually wires: every `status.define(( … ))` map plus `status.semantic-preset`, whose keys
// are read from the mixin in src/lib/styles/_status.scss. `--check` fails instead of writing,
// so a status added to the SCSS without a regenerate cannot ship.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const STYLES = join(ROOT, 'ds-docs/src/styles.scss');
const PRESET = join(ROOT, 'src/lib/styles/_status.scss');
const OUT = join(ROOT, 'ds-docs/src/ds-statuses.d.ts');

const withoutLineComments = (text) => text.replace(/\/\/.*$/gm, '');

// Top-level keys of the Sass map whose opening "(" is at openIndex; nested value maps are skipped.
function topLevelMapKeys(text, openIndex) {
  const keys = [];
  let depth = 0;
  let expectKey = false;
  for (let index = openIndex; index < text.length; index++) {
    const char = text[index];
    if (char === '(') {
      depth++;
      if (depth === 1) expectKey = true;
    } else if (char === ')') {
      depth--;
      if (depth === 0) break;
    } else if (depth === 1 && char === ',') {
      expectKey = true;
    } else if (depth === 1 && expectKey && !/\s/.test(char)) {
      const match = /^['"]?([\w-]+)['"]?\s*:/.exec(text.slice(index));
      if (match) {
        keys.push(match[1]);
        index += match[0].length - 1;
      }
      expectKey = false;
    }
  }
  return keys;
}

const styles = withoutLineComments(readFileSync(STYLES, 'utf8'));
const preset = withoutLineComments(readFileSync(PRESET, 'utf8'));

const keys = [];
for (const match of styles.matchAll(
  /@include\s+status\.(semantic-preset|define\s*\(\s*\()/g,
)) {
  if (match[1] === 'semantic-preset') {
    const mixinAt = preset.indexOf('@mixin semantic-preset');
    if (mixinAt === -1)
      throw new Error('no @mixin semantic-preset in _status.scss');
    const mixin = preset.slice(mixinAt, preset.indexOf('\n}', mixinAt));
    const call = /@include\s+define\s*\(\s*\(/.exec(mixin);
    if (!call) throw new Error('no define map inside @mixin semantic-preset');
    keys.push(...topLevelMapKeys(mixin, call.index + call[0].length - 1));
  } else {
    keys.push(...topLevelMapKeys(styles, match.index + match[0].length - 1));
  }
}
const unique = [...new Set(keys)];
if (unique.length === 0)
  throw new Error('no statuses found in ds-docs/src/styles.scss');

const generated = `// AUTO-GENERATED by tools/extract-statuses.mjs from ds-docs/src/styles.scss - do not edit.
// ds-docs registers its demo status vocabulary so <ds-badge status="…"> autocompletes.
// (External consumers augment '@ids-group-ltd/ids-design-system' instead.)
import 'ds';

declare module 'ds' {
  interface DsStatusRegistry {
${unique.map((key) => `    ${key}: true;`).join('\n')}
  }
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    console.error(
      'extract-statuses: ds-docs/src/ds-statuses.d.ts is missing. Run `npm run extract-statuses`.',
    );
    process.exit(1);
  }
  if (current !== generated) {
    console.error(
      'extract-statuses: ds-statuses.d.ts is out of step with ds-docs/src/styles.scss.\n' +
        '  Run `npm run extract-statuses` and commit the result.',
    );
    process.exit(1);
  }
  console.log(
    `extract-statuses: OK - ${unique.length} statuses match the SCSS.`,
  );
} else {
  writeFileSync(OUT, generated);
  console.log(
    `extract-statuses: wrote ${unique.length} statuses - ${unique.join(', ')}`,
  );
}
