// Builds the React binding package for design-sync:
//   1. regenerates src/lib/icons.gen.ts from the repo's icons.data.ts (no drift)
//   2. esbuild-bundles src/index.ts -> dist/index.js (ESM, react external)
//   3. tsc --emitDeclarationOnly -> dist/**/*.d.ts (the converter's type source)
//
//   node .design-sync/tools/build-bindings.mjs
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const pkgDir = join(repo, '.design-sync', 'react-bindings');
const require_ = createRequire(join(repo, '.ds-sync', 'package.json'));
const esbuild = require_('esbuild');

// ── 1. icons.gen.ts ───────────────────────────────────────────────────────
const iconsSrc = readFileSync(join(repo, 'src/lib/icons/icons.data.ts'), 'utf8');
mkdirSync(join(pkgDir, 'src/lib'), { recursive: true });
const iconNameExport = /export type IconName\b/.test(iconsSrc)
  ? ''
  : '\nexport type IconName = keyof typeof ICONS;\n';
writeFileSync(
  join(pkgDir, 'src/lib/icons.gen.ts'),
  `// GENERATED by build-bindings.mjs from src/lib/icons/icons.data.ts — do not edit.\n${iconsSrc}${iconNameExport}`,
);

// ── 2. bundle ─────────────────────────────────────────────────────────────
await esbuild.build({
  entryPoints: [join(pkgDir, 'src/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  outfile: join(pkgDir, 'dist/index.js'),
  logLevel: 'warning',
});

// ── 3. declarations ───────────────────────────────────────────────────────
const tsc = join(repo, 'node_modules', 'typescript', 'bin', 'tsc');
try {
  execFileSync(process.execPath, [tsc, '-p', join(pkgDir, 'tsconfig.json')], {
    stdio: 'inherit', cwd: pkgDir,
  });
} catch {
  console.error('✗ tsc declaration emit failed — fix type errors above');
  process.exit(1);
}
console.error('✓ react-bindings built: dist/index.js + d.ts tree');
