// Builds the React binding package for design-sync:
//   1. regenerates src/lib/icons.gen.ts from the repo's icons.data.ts (no drift)
//   1b. mirrors the DS's framework-free util modules into src/generated/
//   2. esbuild-bundles src/index.ts -> dist/index.js (ESM, react external)
//   3. tsc --emitDeclarationOnly -> dist/**/*.d.ts (the converter's type source)
//
//   node .design-sync/tools/build-bindings.mjs
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const pkgDir = join(repo, '.design-sync', 'react-bindings');
const require_ = createRequire(join(repo, '.ds-sync', 'package.json'));
const esbuild = require_('esbuild');

// ── 1. icons.gen.ts ───────────────────────────────────────────────────────
const iconsSrc = readFileSync(join(repo, 'src/lib/icons/icons.data.ts'), 'utf8');
mkdirSync(join(pkgDir, 'src/lib'), { recursive: true });
const iconNameExport = /export type IconName\b/.test(iconsSrc)
  ? ''
  : '\nexport type IconName = keyof typeof ICONS;\n';
writeFileSync(
  join(pkgDir, 'src/lib/icons.gen.ts'),
  `// GENERATED by build-bindings.mjs from src/lib/icons/icons.data.ts — do not edit.\n${iconsSrc}${iconNameExport}`,
);

// ── 1b. mirrored util modules ─────────────────────────────────────────────
// Date masking, time parsing and colour maths are pure TS with no Angular
// imports, so the bindings consume the DS's own modules instead of a copy —
// a copy of caret/mask logic diverging silently is exactly the class of drift
// nothing would catch. Rewrites are asserted: an upstream import that changes
// shape fails the build instead of producing a broken mirror.
const MIRRORS = [
  { from: 'src/lib/components/color-picker/color-picker.utils.ts', to: 'color-picker.utils.ts' },
  { from: 'src/lib/components/date-picker/date.util.ts', to: 'date.util.ts' },
  {
    from: 'src/lib/components/time-picker/time.util.ts',
    to: 'time.util.ts',
    // the binding re-declares these types as its own public surface
    rewrites: [[/ from '\.\/time-picker\.types'/, " from '../components/TimePicker'"]],
  },
];
mkdirSync(join(pkgDir, 'src/generated'), { recursive: true });
for (const { from, to, rewrites = [] } of MIRRORS) {
  let source = readFileSync(join(repo, from), 'utf8');
  for (const [pattern, replacement] of rewrites) {
    if (!pattern.test(source)) {
      console.error(`✗ mirror ${from}: rewrite ${pattern} no longer matches — check the upstream imports`);
      process.exit(1);
    }
    source = source.replace(pattern, replacement);
  }
  writeFileSync(
    join(pkgDir, 'src/generated', to),
    `// GENERATED by build-bindings.mjs from ${from} — do not edit.\n${source}`,
  );
}
console.error(`✓ mirrored ${MIRRORS.length} util modules into src/generated/`);

// ── 2. bundle ─────────────────────────────────────────────────────────────
await esbuild.build({
  entryPoints: [join(pkgDir, 'src/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  outfile: join(pkgDir, 'dist/index.js'),
  logLevel: 'warning',
});

// ── 3. declarations ───────────────────────────────────────────────────────
const tsc = join(repo, 'node_modules', 'typescript', 'bin', 'tsc');
try {
  execFileSync(process.execPath, [tsc, '-p', join(pkgDir, 'tsconfig.json')], {
    stdio: 'inherit', cwd: pkgDir,
  });
} catch {
  console.error('✗ tsc declaration emit failed — fix type errors above');
  process.exit(1);
}
console.error('✓ react-bindings built: dist/index.js + d.ts tree');
